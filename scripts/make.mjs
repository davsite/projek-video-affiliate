// One command from a story spec to a checked video.
//   node scripts/make.mjs stories/<id>/story.json [--preview] [--final] [--stills=3.2,10,18] [--no-qa]
//
//   1. resolve   story.json (+ words.json) → src/stories/data/<id>.json, regenerate src/stories/registry.ts
//   2. direct    compile the story (blocking, acting, shots, sound cues) and print the plan; stops on errors
//   3. sound     scripts/sound-story.ts → public/audio/<id>-mix.wav
//   4. render    --preview: 540×960@30 with audio · --final (default): 1080×1920@60, mastered to −14 LUFS
//                (interrupted? run the same command again — finished segments are reused)
//   5. QA        scripts/qa.mjs → out/<id>/qa/ (contact sheets, frame scan, sync, duration)

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const file = args.find((a) => !a.startsWith("--"));
const flag = (k) => args.includes(`--${k}`);
const opt = (k, d) => (args.find((a) => a.startsWith(`--${k}=`)) ?? `=${d ?? ""}`).split("=").slice(1).join("=");
// the director is TypeScript: Node 22.13–22.17 needs the strip-types flag (22.18+ has it on by default)
if (!process.features.typescript) {
  const r = spawnSync(process.execPath, ["--experimental-strip-types", "--no-warnings", ...process.argv.slice(1)], { stdio: "inherit" });
  process.exit(r.status ?? 1);
}
if (!file || !fs.existsSync(file)) {
  console.error("usage: node scripts/make.mjs stories/<id>/story.json [--preview] [--final] [--stills=…] [--no-qa]");
  process.exit(1);
}
const step = (s) => console.log(`\n▶ ${s}`);
const sh = (cmd, a, opts = {}) => {
  const r = spawnSync(cmd, a, { stdio: "inherit", ...opts });
  if (r.status !== 0) { console.error(`✗ ${cmd} ${a.join(" ")} failed`); process.exit(r.status ?? 1); }
};

// 1 ── resolve ───────────────────────────────────────────────────────────────
step("resolve story");
const dir = path.dirname(file);
const story = JSON.parse(fs.readFileSync(file, "utf8"));
if (!/^[a-z0-9-]+$/.test(story.id)) { console.error(`story.id "${story.id}" must use only a-z, 0-9 and "-"`); process.exit(1); }
if (typeof story.words === "string") story.words = JSON.parse(fs.readFileSync(path.join(dir, story.words), "utf8"));
if (!Array.isArray(story.words) || !story.words.length) { console.error("story.words is missing (run scripts/transcribe.mjs first)"); process.exit(1); }
if (!fs.existsSync(path.join("public", story.vo.file))) { console.error(`VO not found: public/${story.vo.file}`); process.exit(1); }
fs.mkdirSync("src/stories/data", { recursive: true });
fs.writeFileSync(`src/stories/data/${story.id}.json`, JSON.stringify(story, null, 1));
const ids = fs.readdirSync("src/stories/data").filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).sort();
const camel = (s) => "s_" + s.replace(/-/g, "_");
fs.writeFileSync("src/stories/registry.ts", `// Generated by scripts/make.mjs — every story in src/stories/data becomes two compositions.\nimport type { Story } from "../kits/characterflow/director/story.ts";\n${ids.map((id) => `import ${camel(id)} from "./data/${id}.json";`).join("\n")}\n\nexport const STORIES: Story[] = [${ids.map((id) => `${camel(id)} as unknown as Story`).join(", ")}];\n`);
const rootFile = "src/Root.tsx", root = fs.readFileSync(rootFile, "utf8");
if (!root.includes("CharacterFlowFilms")) {
  const lastImport = [...root.matchAll(/^import .*;$/gm)].pop(), close = root.lastIndexOf("</>");
  if (!lastImport || close < 0) { console.error(`✗ add <CharacterFlowFilms /> (from "./kits/characterflow/Films.tsx") to ${rootFile} by hand`); process.exit(1); }
  const at = lastImport.index + lastImport[0].length;
  const withEl = root.slice(0, close) + "  <CharacterFlowFilms />\n  " + root.slice(close);
  fs.writeFileSync(rootFile, withEl.slice(0, at) + '\nimport { CharacterFlowFilms } from "./kits/characterflow/Films.tsx";' + withEl.slice(at));
  console.log(`  registered CHARACTER FLOW films in ${rootFile}`);
}
console.log(`  ${story.id}: ${story.words.length} words, ${story.scenes?.length ? `${story.scenes.length + 1} places (${[story.env, ...story.scenes.map((x) => x.env)].join(" → ")})` : `env ${story.env}`}, cast ${story.cast.map((c) => c.look).join(" + ")}, ${story.beats.length} beats`);

// 2 ── direct ────────────────────────────────────────────────────────────────
step("direct (compile the story)");
const { compile } = await import(path.resolve("src/kits/characterflow/director/compile.ts"));
let P;
try { P = compile(story); } catch (e) { console.error(`✗ ${e.message}`); process.exit(1); }
console.log(`  duration ${P.duration}s · ${P.shots.length} shots · ${(P.scenes ?? [P]).reduce((n, x) => n + (x.P ?? x).thoughts.length, 0)} thought bubbles · ${P.sound.length} sound cues`);
for (const sc of P.scenes ?? []) console.log(`  place ${sc.t0.toFixed(2).padStart(6)}–${sc.t1.toFixed(2).padEnd(6)} ${sc.P.env.id} (${sc.P.time}) · ${sc.P.chars.map((c) => c.id).join(" + ")}`);
for (const s of P.shots) console.log(`  ${s.t0.toFixed(2).padStart(6)}–${Math.min(s.t1, P.duration).toFixed(2).padEnd(6)} ${s.kind.padEnd(10)} ${s.a}${s.b ? " → " + s.b : ""}`);
const outDir = path.join("out", story.id);
fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(path.join(outDir, "shots.json"), JSON.stringify({ duration: P.duration, voOffset: P.cues.offset, shots: P.shots.map((s) => ({ kind: s.kind, a: s.a, b: s.b, t0: s.t0, t1: Math.min(s.t1, P.duration) })) }, null, 1));

// 3 ── sound ─────────────────────────────────────────────────────────────────
step("sound");
sh(process.execPath, ["--experimental-strip-types", "--no-warnings", "scripts/sound-story.ts", `src/stories/data/${story.id}.json`]);

// 4 ── render ────────────────────────────────────────────────────────────────
const stills = opt("stills");
if (stills) {
  step("stills");
  // seconds past the end are dropped (with a note) instead of failing the render
  const all = stills.split(",").map((x) => parseFloat(x)).filter((x) => Number.isFinite(x));
  const ok = all.filter((x) => x >= 0 && x < P.duration - 0.05);
  if (ok.length < all.length) console.log(`  (skipped stills past the end of the ${P.duration}s film: ${all.filter((x) => !ok.includes(x)).join(", ")})`);
  if (!ok.length) { console.error("✗ no stills inside the film"); process.exit(1); }
  const secs = ok.map((x) => `${x}s`).join(",");
  sh("node", ["scripts/stills.mjs", path.join(outDir, "stills"), secs, `${story.id}-preview`]);
}
const preview = flag("preview"), final = flag("final") || (!preview && !stills);
let video = null;
if (preview) {
  step("render preview (540×960 @ 30, with audio)");
  video = path.join(outDir, `${story.id}_preview.mp4`);
  sh("npx", ["remotion", "render", `${story.id}-preview`, video, "--codec=h264", "--crf=20", `--concurrency=${opt("concurrency", "6")}`]);
}
if (final) {
  step("render final (1080×1920 @ 60, H.264 + AAC, −14 LUFS)");
  // finished segments survive an interrupted render while the story is unchanged: re-running resumes
  const seg = path.join(outDir, "seg"), stamp = path.join(seg, "story.json");
  const resolved = fs.readFileSync(`src/stories/data/${story.id}.json`, "utf8");
  if (!fs.existsSync(stamp) || fs.readFileSync(stamp, "utf8") !== resolved) fs.rmSync(seg, { recursive: true, force: true });
  fs.mkdirSync(seg, { recursive: true });
  fs.writeFileSync(stamp, resolved);
  video = path.join(outDir, `${story.id}_1080x1920_60fps.mp4`);
  sh("node", ["scripts/render-final.mjs", `--comp=${story.id}-final`, `--out=${video}`, `--vo=public/audio/${story.id}-mix.wav`, "--offset=0", "--parts=4", `--concurrency=${opt("concurrency", "4")}`, `--seg=${seg}`]);
}

// 5 ── QA ────────────────────────────────────────────────────────────────────
if (video && !flag("no-qa")) {
  step("QA");
  sh("node", ["scripts/qa.mjs", video, `--vo=public/${story.vo.file}`, `--offset=${P.cues.offset}`, `--expect=${P.duration}`, `--shots=${path.join(outDir, "shots.json")}`, ...(final ? ["--final"] : [])]);
  // visual review gate: the automated checks never see a hand through a face — someone has to look.
  // REVIEW.md stays "PENDING" until every row is filled; never call the video QA PASS before that.
  const pages = JSON.parse(fs.readFileSync(path.join(outDir, "qa", "qa.json"), "utf8")).contactPages ?? [];
  const rows = [
    "every shot shows the acting person's face (a head bowed over a phone is fine)",
    "the action reads (arm visible for point / wave / explain, body for sit / stand)",
    "props in frame when used (phone, bag)",
    "no camera inside / against furniture, trees, walls or bedding; nobody blocks the lens",
    "no limbs at odd angles; nobody inside furniture or another person; feet on the floor / seat",
    "thought bubbles fully in frame and readable",
    "captions inside the safe area, never over a face",
    "continuity across cuts and place changes (who is where, props, light)",
    "frame errors (black / white / frozen / flicker, burnt highlights)",
    "VO sync; actions land on their words",
    "faces readable on a phone (not too dark)",
    "pacing: no long stretch of one view; no flash cuts",
  ];
  fs.writeFileSync(path.join(outDir, "qa", "REVIEW.md"), [
    `# Visual review — ${story.id} (${path.basename(video)})`, "", "STATUS: PENDING VISUAL REVIEW", "",
    `Look at EVERY page of the 1-fps contact sheet — ${pages.map((p) => `${p.file} (${p.from}–${p.to} s)`).join(", ") || "contact_1fps_*.jpg"} — one tile per second, left→right then top→bottom; together they cover the whole video — and shots_start_mid_end.jpg (open the video for anything doubtful). Tick each page below.`, "",
    ...pages.map((p) => `- [ ] ${p.file} (${p.from}–${p.to} s) seen`), "",
    "Then fill every row with PASS / FIX + what you saw. Set STATUS to PASS only when no FIX is left.", "",
    "| check | verdict | notes |", "|---|---|---|", ...rows.map((r) => `| ${r} | | |`), "",
  ].join("\n"));
  console.log(`  review gate → ${path.join(outDir, "qa", "REVIEW.md")} (PENDING until a visual review is written)`);
}
console.log(`\n✓ done${video ? `: ${video}` : ""}`);
