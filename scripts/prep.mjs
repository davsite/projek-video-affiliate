// Project helper (not part of the kit): steps 1–3 of make.mjs (resolve → direct → sound) without rendering, plus the
// product sound layer for the inserts. CI runs this once, then renders stills or slices of the final.
//   node scripts/prep.mjs stories/<id>/story.json [--no-sound]
import { spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

if (!process.features.typescript) {
  const r = spawnSync(process.execPath, ["--experimental-strip-types", "--no-warnings", ...process.argv.slice(1)], { stdio: "inherit" });
  process.exit(r.status ?? 1);
}
const file = process.argv.slice(2).find((a) => !a.startsWith("--"));
const noSound = process.argv.includes("--no-sound");
if (!file || !fs.existsSync(file)) { console.error("usage: node scripts/prep.mjs stories/<id>/story.json [--no-sound]"); process.exit(1); }
const sh = (cmd, a) => { const r = spawnSync(cmd, a, { stdio: "inherit" }); if (r.status !== 0) { console.error(`✗ ${cmd} ${a.join(" ")}`); process.exit(r.status ?? 1); } };

const dir = path.dirname(file);
const story = JSON.parse(fs.readFileSync(file, "utf8"));
if (typeof story.words === "string") story.words = JSON.parse(fs.readFileSync(path.join(dir, story.words), "utf8"));
if (!fs.existsSync(path.join("public", story.vo.file))) { console.error(`VO not found: public/${story.vo.file}`); process.exit(1); }
fs.mkdirSync("src/stories/data", { recursive: true });
fs.writeFileSync(`src/stories/data/${story.id}.json`, JSON.stringify(story, null, 1));
const ids = fs.readdirSync("src/stories/data").filter((f) => f.endsWith(".json")).map((f) => f.replace(/\.json$/, "")).sort();
const camel = (s) => "s_" + s.replace(/-/g, "_");
fs.writeFileSync("src/stories/registry.ts", `// Generated by scripts/make.mjs — every story in src/stories/data becomes two compositions.\nimport type { Story } from "../kits/characterflow/director/story.ts";\n${ids.map((id) => `import ${camel(id)} from "./data/${id}.json";`).join("\n")}\n\nexport const STORIES: Story[] = [${ids.map((id) => `${camel(id)} as unknown as Story`).join(", ")}];\n`);

const { compile } = await import(path.resolve("src/kits/characterflow/director/compile.ts"));
let P;
try { P = compile(story); } catch (e) { console.error(`✗ ${e.message}`); process.exit(1); }
console.log(`${story.id}: duration ${P.duration}s · ${P.shots.length} shots · ${P.sound.length} sound cues`);
for (const sc of P.scenes ?? []) console.log(`  place ${sc.t0.toFixed(2).padStart(6)}–${sc.t1.toFixed(2).padEnd(6)} ${sc.P.env.id} (${sc.P.time})`);
for (const s of P.shots) console.log(`  ${s.t0.toFixed(2).padStart(6)}–${Math.min(s.t1, P.duration).toFixed(2).padEnd(6)} ${s.kind.padEnd(10)} ${s.a}${s.b ? " → " + s.b : ""}`);
const outDir = path.join("out", story.id);
fs.mkdirSync(outDir, { recursive: true });
// the edit as seen on screen: character shots with the product inserts cut in (QA samples every shot)
const { INSERTS } = await import(path.resolve("src/affiliate/shots.ts"));
const shots = [];
for (const s of P.shots) {
  let pieces = [[s.t0, Math.min(s.t1, P.duration)]];
  for (const ins of INSERTS) pieces = pieces.flatMap(([a, b]) => (ins.t1 <= a || ins.t0 >= b ? [[a, b]] : [[a, ins.t0], [ins.t1, b]].filter(([x, y]) => y - x > 0.05)));
  for (const [a, b] of pieces) shots.push({ kind: s.kind, a: s.a, b: s.b, t0: a, t1: b });
}
for (const ins of INSERTS) shots.push({ kind: `produk:${ins.id}`, a: "produk", t0: ins.t0, t1: Math.min(ins.t1, P.duration) });
shots.sort((x, y) => x.t0 - y.t0);
console.log(`  edit: ${shots.length} shots (${INSERTS.length} product inserts, ${INSERTS.reduce((n, x) => n + x.t1 - x.t0, 0).toFixed(1)} s)`);
fs.writeFileSync(path.join(outDir, "shots.json"), JSON.stringify({ duration: P.duration, voOffset: P.cues.offset, shots }, null, 1));
if (noSound) process.exit(0);
sh(process.execPath, ["--experimental-strip-types", "--no-warnings", "scripts/sound-story.ts", `src/stories/data/${story.id}.json`]);
sh(process.execPath, ["--experimental-strip-types", "--no-warnings", "scripts/product-sfx.ts", `src/stories/data/${story.id}.json`]);
